class ClientContractTests(FakeServerCase):
    """Real subprocess, real pipes: initialize / tools/list / tools/call
    produce the exact schemas the smoke's check functions accept."""

    def test_handshake_list_and_calls_match_the_smoke_contract(self):
        fake = self.write_fake("full")
        client = self.client_session([sys.executable, fake])
        report = ms.Report()
        args = self.args(account="", limit=3)

        ms._handshake(client, report, args)
        tools = ms._list_tools(client, report, args)
        account = ms._call_quota_status(client, report, args)
        ms._call_usage_summary(client, report, args)
        ms._call_check_admission(client, report, account, args)
        ms._adversarial(client, report, tools)

        self.assertFalse(report.failed(), report.checks)
        self.assertEqual(tools, list(EXPECTED_TOOLS))
        self.assertEqual(account, "acct-a")
        checks = self.checks({"checks": report.checks})
        self.assertEqual(checks["initialize"]["detail"], "negotiated 2025-11-25")
        self.assertIn("deny", checks["check_admission"]["detail"])
        self.assertGreater(client.stdout_bytes, 0)
        self.assertEqual(client.notifications, [])

    def test_unknown_tool_and_bad_arguments_are_refused_by_a_real_child(self):
        fake = self.write_fake("full")
        client = self.client_session([sys.executable, fake])
        resp = client.request(1, "tools/call", {"name": "nope", "arguments": {}})
        result, err = client.result_of(resp)
        self.assertIsNone(result)
        self.assertEqual(err, -32602)

    def test_response_deadline_is_enforced_and_child_is_reaped(self):
        fake = self.write_fake("hang")
        client = self.client_session([sys.executable, fake], response_timeout=0.3)

        start = time.monotonic()
        with self.assertRaises(ms.SmokeError) as caught:
            client.request(1, "initialize", {"protocolVersion": "2025-11-25"})
        self.assertEqual(caught.exception.code, "response_timeout")
        self.assertLess(time.monotonic() - start, 5)

        client.close()
        self.assertIsNotNone(client._proc.poll(), "hung child was not reaped")

    def test_nonposix_teardown_uses_popen_methods_with_no_sigkill(self):
        """The Windows branch of close() must never touch signal.SIGKILL."""
        fake = self.write_fake("hang")
        client = self.client_session([sys.executable, fake], term_timeout=0.2)
        self.patch("TERM_GRACE", 0.2)
        self.patch("KILL_GRACE", 0.2)

        previous = ms.os.name
        ms.os.name = "nt"  # make close() take the non-POSIX (Windows) branch
        try:
            start = time.monotonic()
            client.close()
            elapsed = time.monotonic() - start
        finally:
            ms.os.name = previous

        self.assertLess(elapsed, 5)
        self.assertIsNotNone(client._proc.poll(), "child survived non-POSIX teardown")

    def test_oversized_stdout_line_is_bounded(self):
        self.patch("MAX_LINE_BYTES", 256)
        fake = self.write_fake("oversize", oversize=4096)
        client = self.client_session([sys.executable, fake])

        with self.assertRaises(ms.SmokeError) as caught:
            client.request(1, "initialize", {"protocolVersion": "2025-11-25"})
        self.assertEqual(caught.exception.code, "oversized_stdout_line")
        # The partial line is capped at the chunk that triggered the check --
        # it is never accumulated without bound.
        self.assertLessEqual(len(client._buf), ms.STDOUT_CHUNK)

    def test_child_that_closes_stdout_reports_server_closed_stdout(self):
        fake = self.write_fake("exit_zero")
        client = self.client_session([sys.executable, fake])

        with self.assertRaises(ms.SmokeError) as caught:
            client.request(1, "initialize", {"protocolVersion": "2025-11-25"})
        self.assertIn(caught.exception.code, ("server_closed_stdout", "stdin_closed"))

    def test_stdin_closed_child_is_reported_and_never_leaks_stderr(self):
        fake = self.write_fake("exit_nonzero")
        client = self.client_session([sys.executable, fake])

        with self.assertRaises(ms.SmokeError) as caught:
            client.request(1, "initialize", {"protocolVersion": "2025-11-25"})
        self.assertIn(caught.exception.code, ("server_closed_stdout", "stdin_closed"))
        # stderr is drained and counted, but never retained, echoed or
        # exposed by any accessor -- so the sentinel cannot reach a report.
        deadline = time.monotonic() + 5
        while client.stderr_bytes == 0 and time.monotonic() < deadline:
            time.sleep(0.02)
        self.assertGreater(client.stderr_bytes, 0)
        self.assertFalse(hasattr(client, "_stderr_head"))
        self.assertFalse(hasattr(client, "stderr_preview"))
        self.assertNotIn(SENTINEL, json.dumps(
            {"stderr_bytes": client.stderr_bytes, "code": caught.exception.code}))


class SourcePortabilityTests(unittest.TestCase):
    """Static guards for the portability contract (cheap, no child process)."""

    def test_no_posix_only_primitives_in_the_source(self):
        source = (HERE / "mcp-smoke.py").read_text(encoding="utf-8")
        tree = ast.parse(source)
        # select() over a pipe fd is POSIX-only; the reader must use a thread.
        imports = {alias.name for node in ast.walk(tree)
                    if isinstance(node, ast.Import) for alias in node.names}
        self.assertNotIn("select", imports)
        self.assertIn("queue", imports)
        self.assertNotIn("os.set_blocking", source)
        self.assertNotIn("stderr_preview", source)

        # signal.SIGKILL does not exist on Windows, so it may be referenced
        # exactly once, inside StdioClient._kill, behind an os.name guard.
        sites = [node for node in ast.walk(tree)
                 if isinstance(node, ast.Attribute) and node.attr == "SIGKILL"]
        self.assertEqual(len(sites), 1, "SIGKILL referenced outside a guard")
        owner = None
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.lineno <= sites[0].lineno <= (
                node.end_lineno or node.lineno
            ):
                if owner is None or node.lineno > owner.lineno:
                    owner = node
        self.assertIsNotNone(owner)
        self.assertEqual(owner.name, "_kill")
        guard = owner.body[0]
        self.assertIsInstance(guard, ast.If)
        self.assertEqual(
            ast.unparse(guard.test).replace('"', "'"), "os.name == 'posix'"
        )

