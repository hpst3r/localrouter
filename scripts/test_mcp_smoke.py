#!/usr/bin/env python3
"""Hermetic, offline tests for ``scripts/mcp-smoke.py``.

Every test drives a **real child process** over real stdin/stdout pipes: a
generated fake ``localrouter mcp`` stdio server (a small Python program) is
written into a private temporary directory and launched either

* through its ``#!/usr/bin/env python3`` shebang, exactly as the smoke's
  ``--binary PATH`` path would launch the real adapter (POSIX), or
* through ``[sys.executable, script]`` (any platform), for the classes that
  exercise ``StdioClient`` and the protocol/check helpers directly.

Nothing here talks to a router, a network, or an LLM. Fake servers live under
``$TMPDIR`` (or ``~/.hermes/cache/scratch``), never under the system temp dir.
Every spawned process is either reaped by the smoke's own ``close()`` or
force-killed in a test cleanup, so a hung fake can never leak.

Run with:  python3 -m unittest discover -s scripts -p 'test_mcp_smoke.py'
or:        python3 scripts/test_mcp_smoke.py
"""

from __future__ import annotations

import ast
import contextlib
import importlib.util
import io
import json
import os
import pathlib
import signal
import subprocess
import sys
import tempfile
import time
import unittest

HERE = pathlib.Path(__file__).resolve().parent
POSIX = os.name == "posix"

SENTINEL = "SENTINEL-KEY-DO-NOT-LEAK-abc123"
EXPECTED_TOOLS = ("quota_status", "usage_summary", "check_admission")

# The system temp dir is never used for fake servers or child artefacts.
_FORBIDDEN_TEMP = tuple(
    os.path.abspath(p) for p in ("/tmp", "/var/tmp") if os.path.isabs(p)
)


def _load_module():
    spec = importlib.util.spec_from_file_location("mcp_smoke", HERE / "mcp-smoke.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


ms = _load_module()


