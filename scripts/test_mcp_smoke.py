# Fake stdio MCP server (generated per test)
# ---------------------------------------------------------------------------

FAKE_TEMPLATE = '''#!/usr/bin/env python3
"""Fake `localrouter mcp` stdio server, generated by test_mcp_smoke.py.

Speaks just enough newline-delimited JSON-RPC 2.0 to satisfy the smoke
harness. Reads nothing and opens no socket: --url/--key-file on argv (and any
leading "mcp" subcommand word) are accepted and ignored.
"""

import json
import os
import sys
import time

MODE = @@MODE@@
OVERSIZE = @@OVERSIZE@@

_TOOLS = ("quota_status", "usage_summary", "check_admission")
_ACCOUNTS = [
    {"id": "acct-a", "provider": "codex", "status": "ok"},
    {"id": "acct-b", "provider": "claude", "status": "ok"},
]


def _write(text):
    sys.stdout.write(text)
    sys.stdout.flush()


def _send(obj):
    _write(json.dumps(obj, separators=(",", ":")) + "\\n")


def _result(msg_id, result):
    _send({"jsonrpc": "2.0", "id": msg_id, "result": result})


def _error(msg_id, code, message):
    _send({"jsonrpc": "2.0", "id": msg_id, "error": {"code": code, "message": message}})


def _tool_result(msg_id, structured, is_error=False):
    _result(msg_id, {
        "content": [{"type": "text", "text": "ok"}],
        "structuredContent": structured,
        "isError": is_error,
    })


def _tools():
    return [
        {"name": name, "description": "fake " + name,
         "inputSchema": {"type": "object", "properties": {}}}
        for name in _TOOLS
    ]


def _record_pids(extra=()):
    path = os.environ.get("MCP_FAKE_PIDS")
    if not path:
        return
    with open(path, "w", encoding="utf-8") as handle:
        for pid in (os.getpid(),) + tuple(extra):
            handle.write("%d\\n" % pid)


def _ignore_sigterm():
    # POSIX only: makes teardown exhaust the graceful window and reach kill().
    if os.name == "posix":
        import signal
        signal.signal(signal.SIGTERM, signal.SIG_IGN)


def _hang():
    _ignore_sigterm()
    while True:
        time.sleep(0.05)


def _call(msg_id, params):
    name = params.get("name")
    arguments = params.get("arguments") or {}
    if name == "quota_status":
        _tool_result(msg_id, {"schema_version": 1, "accounts": _ACCOUNTS, "clients": []})
        return
    if name == "usage_summary":
        limit = arguments.get("limit")
        if not isinstance(limit, int) or isinstance(limit, bool):
            _error(msg_id, -32602, "invalid arguments: limit must be an integer")
            return
        rows = [
            {"model": "m-1", "requests": 2, "input_tokens": 10},
            {"model": "m-2", "requests": 1, "input_tokens": 5},
        ]
        rows = rows[:max(0, min(limit, len(rows)))]
        _tool_result(msg_id, {"schema_version": 1, "rows": rows})
        return
    if name == "check_admission":
        if arguments.get("class") == "bogus":
            _tool_result(msg_id, {"decision": "deny", "reason": "unknown class"})
            return
        _tool_result(msg_id, {
            "decision": "deny",
            "reason": "no budget",
            "class": arguments.get("class"),
            "account": arguments.get("account"),
        })
        return
    _error(msg_id, -32602, "tool not found")


def main():
    if MODE == "exit_nonzero":
        # A binary without an `mcp` subcommand: usage on stderr, nonzero exit.
        sys.stderr.write("localrouter: unknown command " + @@SENTINEL@@ + "\\n")
        sys.stderr.flush()
        return 3
    if MODE == "exit_zero":
        return 0
    if MODE == "hang":
        _record_pids()
        _hang()
    if MODE == "hang_child":
        import subprocess
        child = subprocess.Popen(
            [sys.executable, "-c", "import time; time.sleep(300)"])
        _record_pids((child.pid,))
        _hang()
    if MODE == "anomaly":
        _write("localrouter: warming up\\n")  # non-JSON chatter on stdout
    if MODE == "oversize":
        _write("x" * OVERSIZE + "\\n")
    while True:
        line = sys.stdin.readline()
        if not line:
            return 0
        line = line.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except ValueError:
            continue
        method = msg.get("method")
        msg_id = msg.get("id")
        params = msg.get("params") or {}
        if method == "initialize":
            _result(msg_id, {
                "protocolVersion": "2025-11-25",
                "capabilities": {},
                "serverInfo": {"name": "fake-localrouter", "version": "test"},
            })
        elif method == "tools/list":
            _result(msg_id, {"tools": _tools()})
        elif method == "tools/call":
            _call(msg_id, params)
        elif msg_id is not None:
            _error(msg_id, -32601, "method not found")
        # notifications carry no id and need no reply


if __name__ == "__main__":
    sys.exit(main())
'''


def _tmp_base():
    """A scratch directory that is not the system temp dir."""
    candidates = [
        os.environ.get("TMPDIR"),
        os.path.join(os.path.expanduser("~"), ".hermes", "cache", "scratch"),
    ]
    for candidate in candidates:
        if not candidate:
            continue
        candidate = os.path.abspath(candidate)
        if candidate in _FORBIDDEN_TEMP or candidate.startswith(
            tuple(p + os.sep for p in _FORBIDDEN_TEMP)
        ):
            continue
        try:
            os.makedirs(candidate, exist_ok=True)
        except OSError:
            continue
        return candidate
    raise RuntimeError("no non-/tmp scratch directory for fake MCP servers")


def _force_kill(pid):
    """Best-effort kill used only by test cleanup; never raises."""
    try:
        if POSIX:
            os.kill(pid, signal.SIGKILL)
        else:  # pragma: no cover - no Windows runtime here
            subprocess.run(["taskkill", "/F", "/PID", str(pid)],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except OSError:
        pass


class FakeServerCase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="mcp-smoke-test-", dir=_tmp_base())
        self.addCleanup(self._tmp.cleanup)
        self.dir = pathlib.Path(self._tmp.name)

    # -- helpers ----------------------------------------------------------

    def patch(self, name, value):
        original = getattr(ms, name)
        setattr(ms, name, value)
        self.addCleanup(setattr, ms, name, original)

    def fast_teardown(self, term=0.2, grace=0.2):
        """Shrink the smoke's teardown windows so hang tests stay fast."""
        self.patch("DEFAULT_TERM_TIMEOUT", term)
        self.patch("TERM_GRACE", grace)
        self.patch("KILL_GRACE", grace)

    def write_fake(self, mode, oversize=4096, name="fake-mcp"):
        body = (
            FAKE_TEMPLATE.replace("@@MODE@@", repr(mode))
            .replace("@@OVERSIZE@@", str(oversize))
            .replace("@@SENTINEL@@", repr(SENTINEL))
        )
        path = self.dir / name
        path.write_text(body, encoding="utf-8")
        if POSIX:
            os.chmod(path, 0o755)
        return str(path)

    def track_pids(self, pidfile):
        """Record every pid the fake writes and force-kill any survivor."""
        def reap():
            try:
                text = pidfile.read_text(encoding="utf-8")
            except OSError:
                return
            for token in text.split():
                try:
                    pid = int(token)
                except ValueError:
                    continue
                _force_kill(pid)

        self.addCleanup(reap)
        previous = os.environ.get("MCP_FAKE_PIDS")
        os.environ["MCP_FAKE_PIDS"] = str(pidfile)

        def restore():
            if previous is None:
                os.environ.pop("MCP_FAKE_PIDS", None)
            else:
                os.environ["MCP_FAKE_PIDS"] = previous

        self.addCleanup(restore)
        return pidfile

    def run_tool(self, argv):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = ms.main(list(argv))
        return code, out.getvalue(), err.getvalue()

    def smoke_argv(self, binary, **overrides):
        argv = [
            "--binary", binary,
            "--url", "http://127.0.0.1:8787",
            "--json",
            "--response-timeout", "2",
            "--overall-timeout", "20",
        ]
        for flag, value in overrides.items():
            argv.extend(["--" + flag.replace("_", "-"), str(value)])
        return argv

    @staticmethod
    def checks(report):
        return {check["check"]: check for check in report["checks"]}

    def report(self, out):
        return json.loads(out)

    def client_session(self, argv, response_timeout=2.0, overall=20.0, term_timeout=0.2):
        client = ms.StdioClient(argv, response_timeout, time.monotonic() + overall,
                                term_timeout=term_timeout)
        client.start()
        self.addCleanup(client.close)
        return client

    @staticmethod
    def args(**overrides):
        argv = ["--binary", sys.executable, "--url", "http://127.0.0.1:8787", "--json"]
        for flag, value in overrides.items():
            argv.extend(["--" + flag.replace("_", "-"), str(value)])
        return ms.parse_args(argv)


