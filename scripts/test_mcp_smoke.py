@unittest.skipUnless(POSIX, "the --binary path execs the script via its shebang")
class EndToEndRunTests(FakeServerCase):
    def test_full_session_passes_with_three_tools_and_deny(self):
        fake = self.write_fake("full")
        code, out, err = self.run_tool(self.smoke_argv(fake))

        self.assertEqual(code, 0, out + err)
        report = self.report(out)
        self.assertTrue(report["ok"], report)
        self.assertEqual(report["exit_code"], 0)
        self.assertNotIn(SENTINEL, out + err)

        checks = self.checks(report)
        self.assertEqual(checks["initialize"]["status"], "pass")
        self.assertEqual(checks["initialize"]["detail"], "negotiated 2025-11-25")
        self.assertEqual(checks["server_info"]["status"], "pass")
        self.assertEqual(checks["tools_list"]["status"], "pass")
        self.assertEqual(checks["tools_list"]["detail"],
                         ",".join(sorted(EXPECTED_TOOLS)))
        self.assertEqual(checks["quota_status"]["status"], "pass")
        self.assertIn("acct-a", checks["quota_status"]["detail"])
        self.assertEqual(checks["usage_summary"]["status"], "pass")
        # A deny is a normal dry-run outcome, never a failure.
        self.assertEqual(checks["check_admission"]["status"], "pass")
        self.assertIn("deny", checks["check_admission"]["detail"])
        for name in ("unknown_tool_errors", "bad_args_errors", "bad_enum_handled",
                     "stdout_is_json_only"):
            self.assertEqual(checks[name]["status"], "pass", name)
        self.assertFalse(report["checks"][-1]["status"] == "fail")
        self.assertGreater(report["stdout_bytes"], 0)
        self.assertEqual(report["stderr_bytes"], 0)

    def test_known_account_flag_passes_and_unknown_account_only_warns(self):
        fake = self.write_fake("full")

        code, out, err = self.run_tool(self.smoke_argv(fake, account="acct-b"))
        self.assertEqual(code, 0, out + err)
        known = self.checks(self.report(out))["account"]
        self.assertEqual(known["status"], "pass")

        code, out, err = self.run_tool(self.smoke_argv(fake, account="ghost-account"))
        self.assertEqual(code, 0, out + err)
        report = self.report(out)
        unknown = self.checks(report)["account"]
        self.assertEqual(unknown["status"], "warn")
        self.assertIn("ghost-account", unknown["detail"])
        # A warning is not a failed check, and quota_status itself still passed.
        self.assertTrue(report["ok"], report)
        self.assertEqual(self.checks(report)["quota_status"]["status"], "pass")

    def test_usage_summary_limit_is_honoured(self):
        fake = self.write_fake("full")
        code, out, err = self.run_tool(self.smoke_argv(fake, limit=1))
        self.assertEqual(code, 0, out + err)
        detail = self.checks(self.report(out))["usage_summary"]["detail"]
        self.assertTrue(detail.startswith("1 row(s)"), detail)

    def test_missing_binary_is_a_precondition_error(self):
        missing = str(self.dir / "does-not-exist-localrouter")
        code, out, err = self.run_tool(self.smoke_argv(missing))
        self.assertEqual(code, 2)
        self.assertIn("binary_not_found", out + err)
        self.assertEqual(self.checks(self.report(out))["preconditions"]["status"], "fail")

    def test_missing_key_file_is_a_precondition_error(self):
        fake = self.write_fake("full")
        code, out, err = self.run_tool(
            self.smoke_argv(fake, key_file=str(self.dir / "no-such.key")))
        self.assertEqual(code, 2)
        self.assertIn("key_file_missing", out + err)

    def test_binary_without_mcp_subcommand_is_server_unavailable(self):
        fake = self.write_fake("exit_nonzero")
        code, out, err = self.run_tool(self.smoke_argv(fake))

        self.assertEqual(code, 1)
        self.assertNotIn(SENTINEL, out + err)  # stderr is never echoed
        report = self.report(out)
        self.assertFalse(report["ok"])
        checks = self.checks(report)
        self.assertEqual(checks["session"]["status"], "fail")
        self.assertIn("subprocess exit 3", checks["session"]["detail"])
        self.assertEqual(checks["verdict"]["detail"], "server_unavailable")

    def test_binary_that_exits_zero_early_is_not_a_pass(self):
        fake = self.write_fake("exit_zero")
        code, out, err = self.run_tool(self.smoke_argv(fake))

        self.assertEqual(code, 1)
        checks = self.checks(self.report(out))
        self.assertEqual(checks["session"]["status"], "fail")
        self.assertTrue(
            any(token in checks["session"]["detail"]
                for token in ("server_closed_stdout", "stdin_closed")),
            checks["session"],
        )
        self.assertEqual(checks["verdict"]["detail"], "server_unavailable")

    def test_non_json_stdout_line_fails_the_run(self):
        fake = self.write_fake("anomaly")
        code, out, err = self.run_tool(self.smoke_argv(fake))

        self.assertEqual(code, 1)
        report = self.report(out)
        checks = self.checks(report)
        self.assertEqual(checks["stdout_is_json_only"]["status"], "fail")
        self.assertIn("non-JSON line", checks["stdout_is_json_only"]["detail"])
        # Everything else in the session still succeeded.
        self.assertEqual(checks["tools_list"]["status"], "pass")
        self.assertEqual(checks["check_admission"]["status"], "pass")

    def test_hung_server_times_out_and_is_cleaned_up(self):
        self.fast_teardown()
        pidfile = self.track_pids(self.dir / "pids.txt")
        fake = self.write_fake("hang")

        start = time.monotonic()
        code, out, err = self.run_tool(
            self.smoke_argv(fake, response_timeout=0.3, overall_timeout=20))
        elapsed = time.monotonic() - start

        self.assertEqual(code, 1)
        checks = self.checks(self.report(out))
        self.assertEqual(checks["session"]["status"], "fail")
        self.assertIn("response_timeout", checks["session"]["detail"])
        self.assertLess(elapsed, 10, "teardown was not bounded: %.2fs" % elapsed)

        pids = [int(t) for t in pidfile.read_text(encoding="utf-8").split()]
        self.assertEqual(len(pids), 1)
        self.assert_child_gone(pids[0])

    @unittest.skipUnless(POSIX, "POSIX process groups")
    def test_hung_server_process_group_is_killed(self):
        self.fast_teardown()
        pidfile = self.track_pids(self.dir / "pids.txt")
        fake = self.write_fake("hang_child")

        code, out, err = self.run_tool(
            self.smoke_argv(fake, response_timeout=0.3, overall_timeout=20))

        self.assertEqual(code, 1)
        pids = [int(t) for t in pidfile.read_text(encoding="utf-8").split()]
        self.assertEqual(len(pids), 2, pids)
        for pid in pids:  # the whole group dies, not just the direct child
            self.assert_child_gone(pid)

    def assert_child_gone(self, pid):
        deadline = time.monotonic() + 5
        while True:
            try:
                os.kill(pid, 0)
            except ProcessLookupError:
                return
            except PermissionError:  # pragma: no cover - not our process
                return
            if time.monotonic() >= deadline:
                self.fail("child %d survived teardown" % pid)
            time.sleep(0.05)


